WHO = {k: QX[k]["кто"] for k in QX}
DECIDED = {k: QX[k]["решение"] for k in QX if QX[k].get("решение")}

def body(t): return re.sub(r'^\d+(\.\d+)*\.?\s*', '', t.strip())
def norm(t): return re.sub(r'[\s_«»"“”.,;:()\-–]+', ' ', body(t).lower()).strip()
def src(cells, ks): return [f"{k} {FORM[k]} (п. {cells[k]['n']})" for k in ks]

items = []
for i, r in enumerate(rows):
    if i == 11:
        c = dict(r["cells"]); h4 = c.pop("Н4"); items += [("11", c), ("11b", {"Н4": h4})]
    else: items.append((str(i), r["cells"]))

# единая нумерация черновика
num, sec, sub, subsub = {}, 0, 0, 0
for key, cells in items:
    n = next(iter(cells.values()))["n"]
    if key == "0": num[key] = None; continue
    if A[key]["status"] == "служебное" and n.count(".") == 0:
        sec = int(n); sub = 0; num[key] = str(sec); continue
    p = n.split(".")
    if len(p) == 2: sub = int(p[1]); subsub = 0; num[key] = f"{sec}.{sub}"
    else: subsub += 1; num[key] = f"{sec}.{sub}.{subsub}"
NOTICE, RAST = num["27"], num["28"]

seen_q = {}
def qlines(qs, here):
    L = []
    for q in qs:
        if q in seen_q:
            L.append(f"См. ВОПРОС № {q} (к п. {seen_q[q]})."); continue
        seen_q[q] = here
        head, opts = Q[q]
        if q in DECIDED:
            L.append(f"✅ ВОПРОС № {q} РЕШЁН: {head}"); L += ["   " + x for x in DECIDED[q].split("\n")]; continue
        L.append(f"❓ ВОПРОС КОМАНДЕ № {q} ({WHO[q]}): {head}")
        L += ["   " + o for o in opts]
        L.append("   Ответ: ____________________")
    return L

